export function parseConditioningAndCardio(day) {
  if (!day) return [];

  const items = [];

  // 1. Conditioning
  const condRaw = day.bodyweight_conditioning || '';
  if (
    condRaw &&
    !condRaw.toLowerCase().includes('no conditioning') &&
    !condRaw.toLowerCase().includes('optional relaxed walk')
  ) {
    let clean = condRaw.replace(/^\d+\s+easy\s+rounds:\s*/i, '');
    clean = clean.replace(/Rest as needed\.?/i, '');
    const parts = clean.split(';').map((p) => p.trim()).filter(Boolean);

    parts.forEach((p, idx) => {
      const s = p.replace(/^[ .;]+|[ .;]+$/g, '');
      if (!s || s.toLowerCase().includes('optional') || s.toLowerCase().startsWith('skip ')) return;

      const m = s.match(/(\d+[\s\u00d7xX*–-]\S+.*|\d+\s*(?:sec|min|each|reps?).*)/i);
      let name = s;
      let presc = '2–3 rounds controlled';
      if (m) {
        name = s.slice(0, m.index).replace(/[:;,]+$/, '').trim();
        presc = s.slice(m.index).replace(/[ .;]+$/, '').trim();
      }

      const lower = name.toLowerCase();
      let mediaKey = Object.keys(CONDITIONING_MEDIA).find((k) => lower.includes(k)) || 'stepper';
      const media = CONDITIONING_MEDIA[mediaKey];

      items.push({
        id: `cond_${idx}`,
        type: 'conditioning',
        index: idx,
        name: media?.display_name || name.charAt(0).toUpperCase() + name.slice(1),
        prescription: presc,
        calories: 35,
        media: media || { display_name: name },
        gif_url: media?.gif_url || media?.images?.[0] || '',
      });
    });
  }

  // 2. Cardio
  const cardioRaw = day.cardio || '';
  if (
    cardioRaw &&
    !cardioRaw.toLowerCase().includes('none') &&
    !cardioRaw.toLowerCase().includes('optional relaxed')
  ) {
    const s = cardioRaw.replace(/^[ .;]+|[ .;]+$/g, '');
    const m = s.match(/(\d+[\s\u00d7xX*–-].*)/i);
    let name = s;
    let presc = '15–20 min steady';
    if (m) {
      name = s.slice(0, m.index).replace(/[:;,]+$/, '').trim();
      presc = s.slice(m.index).replace(/[ .;]+$/, '').trim();
    }

    const lower = name.toLowerCase();
    let mediaKey = 'treadmill';
    if (lower.includes('cross') || lower.includes('trainer') || lower.includes('elliptical')) {
      mediaKey = 'cross trainer';
    } else if (lower.includes('cycle') || lower.includes('bike')) {
      mediaKey = 'cycle';
    } else if (lower.includes('walk')) {
      mediaKey = 'walk';
    }
    const media = CONDITIONING_MEDIA[mediaKey];

    items.push({
      id: 'cardio_0',
      type: 'cardio',
      index: 0,
      name: media?.display_name || name.charAt(0).toUpperCase() + name.slice(1),
      prescription: presc,
      calories: 75,
      media: media || { display_name: name },
      gif_url: media?.gif_url || media?.images?.[0] || '',
    });
  }

  return items;
}
